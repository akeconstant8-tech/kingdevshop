// Order rules shared by the cart (display) and the server (source of truth).
// The server always recomputes prices and delivery fees from this module and the
// product table — amounts sent by the browser are never trusted.
// Pure module (only depends on zod) so it can be unit-tested with `node --test`.
import { z } from "zod";

export const WHATSAPP_NUMBER = "2250711257655";
export const MAX_QTY_PER_ITEM = 50;

export const DELIVERY_OPTIONS: readonly { city: string; fee: number }[] = [
  { city: "Grand-Bassam", fee: 3000 },
  { city: "Anyama", fee: 2500 },
  { city: "Abobo", fee: 2000 },
  { city: "Cocody", fee: 2000 },
  { city: "Bingerville", fee: 2000 },
  { city: "Adjamé", fee: 1500 },
  { city: "Marcory", fee: 1500 },
  { city: "Treichville", fee: 1500 },
  { city: "Koumassi", fee: 1500 },
  { city: "Port-Bouët", fee: 2000 },
  { city: "Attécoubé", fee: 1500 },
  { city: "Plateau", fee: 2000 },
];

export const customerSchema = z.object({
  name: z.string().trim().min(2, "Nom trop court").max(80, "Nom trop long"),
  phone: z
    .string()
    .trim()
    .min(8, "Numéro invalide")
    .max(20, "Numéro trop long")
    .regex(/^[0-9 +().-]+$/, "Numéro invalide"),
  address: z.string().trim().min(5, "Adresse trop courte").max(250, "Adresse trop longue"),
});
export type CustomerInfo = z.infer<typeof customerSchema>;

export const orderInputSchema = z.object({
  // Generated by the browser once per cart: re-sending the same order (double click,
  // network retry) hits the primary key instead of creating a duplicate.
  id: z.string().uuid("Identifiant de commande invalide"),
  customer: customerSchema,
  delivery_city: z.string().min(1, "Choisissez une ville de livraison"),
  items: z
    .array(
      z.object({
        id: z.string().uuid("Article invalide"),
        qty: z
          .number()
          .int()
          .min(1, "Quantité invalide")
          .max(MAX_QTY_PER_ITEM, `Quantité maximale : ${MAX_QTY_PER_ITEM} par article`),
      }),
    )
    .min(1, "Votre panier est vide")
    .max(100, "Trop d'articles dans le panier"),
});
export type OrderInput = z.infer<typeof orderInputSchema>;

export type CatalogProduct = { id: string; name: string; price: number | string; in_stock: boolean };
export type OrderLine = { id: string; name: string; price: number; qty: number };
export type ComputedOrder = {
  items: OrderLine[];
  subtotal: number;
  deliveryCity: string;
  deliveryFee: number;
  total: number;
};

export function findDelivery(city: string) {
  return DELIVERY_OPTIONS.find((o) => o.city === city) ?? null;
}

// Builds the order from the live catalog: current prices, stock check, merged duplicate
// lines and the delivery fee of the chosen city. Throws a message meant for the customer.
export function computeOrder(
  items: { id: string; qty: number }[],
  deliveryCity: string,
  catalog: CatalogProduct[],
): ComputedOrder {
  const delivery = findDelivery(deliveryCity);
  if (!delivery) throw new Error("Ville de livraison inconnue. Choisissez une ville dans la liste.");

  const qtyById = new Map<string, number>();
  for (const i of items) qtyById.set(i.id, (qtyById.get(i.id) ?? 0) + i.qty);

  const byId = new Map(catalog.map((p) => [p.id, p]));
  const lines: OrderLine[] = [];
  for (const [id, qty] of qtyById) {
    const p = byId.get(id);
    if (!p) throw new Error("Un article de votre panier n'existe plus. Retirez-le puis réessayez.");
    if (!p.in_stock) throw new Error(`« ${p.name} » est en rupture de stock. Retirez-le puis réessayez.`);
    if (qty > MAX_QTY_PER_ITEM) throw new Error(`Quantité maximale : ${MAX_QTY_PER_ITEM} par article (« ${p.name} »).`);
    lines.push({ id, name: p.name, price: Number(p.price), qty });
  }

  const subtotal = lines.reduce((s, l) => s + l.price * l.qty, 0);
  return { items: lines, subtotal, deliveryCity: delivery.city, deliveryFee: delivery.fee, total: subtotal + delivery.fee };
}

export function formatFcfa(amount: number) {
  return `${Number(amount).toLocaleString("fr-FR")} FCFA`;
}

export function orderReference(orderId: string) {
  return orderId.slice(0, 8).toUpperCase();
}

export function deliveryAddressLine(address: string, order: Pick<ComputedOrder, "deliveryCity" | "deliveryFee">) {
  return `${address} — Livraison ${order.deliveryCity} (${formatFcfa(order.deliveryFee)})`;
}

export function buildWhatsAppMessage(orderId: string, order: ComputedOrder, customer: CustomerInfo) {
  return [
    "*Nouvelle commande — King Dev Shop* 🛏️",
    `Réf. commande : ${orderReference(orderId)}`,
    "",
    "*Client :*",
    `• Nom : ${customer.name}`,
    `• Téléphone : ${customer.phone}`,
    `• Adresse : ${customer.address}`,
    `• Ville de livraison : ${order.deliveryCity}`,
    "",
    "*Articles :*",
    ...order.items.map((i) => `• ${i.name} × ${i.qty} — ${formatFcfa(i.price * i.qty)}`),
    "",
    `Sous-total : ${formatFcfa(order.subtotal)}`,
    `Livraison (${order.deliveryCity}) : ${formatFcfa(order.deliveryFee)}`,
    `*Total TTC : ${formatFcfa(order.total)}*`,
    "",
    "Merci de me confirmer la disponibilité.",
  ].join("\n");
}

export function whatsappUrl(text: string) {
  return `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(text)}`;
}

// RFC 4122 v4. crypto.randomUUID only exists on HTTPS/localhost; getRandomValues
// also works when the shop is opened over the local network (http://192.168…).
export function newOrderId() {
  if (typeof crypto.randomUUID === "function") return crypto.randomUUID();
  const b = crypto.getRandomValues(new Uint8Array(16));
  b[6] = (b[6] & 0x0f) | 0x40;
  b[8] = (b[8] & 0x3f) | 0x80;
  const h = Array.from(b, (x) => x.toString(16).padStart(2, "0")).join("");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}
